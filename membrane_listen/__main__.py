"""Command line: ``python -m membrane_listen [--out DIR] [--check]``.

Builds the six SYNTHETIC scene WAV files (seed 42, 8000 Hz) and prints
the measured numbers. With ``--check`` nothing is written; the scenes
are regenerated in memory and compared byte for byte with the files in
DIR (exit status 1 on any difference).
"""

import argparse
import os
import sys

from . import __version__
from .scenes import SCENE_FILES, build_scenes


def describe(name, info):
    if name.startswith("wave_stereo"):
        return ("sensors %g and %g, phase gap measured %+.4f rad "
                "(expected %+.4f)" % (info["sensors"][0], info["sensors"][1],
                                      info["gap_mean"], info["gap_expected"]))
    if name.startswith("wave_"):
        return ("k_est %+.2f  omega %+.3f  coherence %.3f  wave-order %.3f"
                % (info["k_est"], info["omega"], info["coherence"],
                   info["wave_order"]))
    if name == "heart.wav":
        return ("%d thumps in %.1f s, pacemaker every %.2f s, sensor delay "
                "%.2f s" % (info["thumps"], info["seconds"], info["period_s"],
                            info["delay_s"]))
    return ("left %.2f s, right %.2f s, spread %.2f s, %.1f s stereo"
            % (info["left_delay_s"], info["right_delay_s"], info["spread_s"],
               info["seconds"]))


def main(argv=None):
    parser = argparse.ArgumentParser(
        prog="membrane_listen", description=__doc__.split("\n\n")[0])
    parser.add_argument("--out", default="wav",
                        help="directory for the WAV files (default: wav)")
    parser.add_argument("--check", action="store_true",
                        help="compare regenerated bytes with files in DIR")
    parser.add_argument("--version", action="version",
                        version="membrane-listen " + __version__)
    args = parser.parse_args(argv)
    print("membrane-listen %s (SYNTHETIC sonification, seed 42, 8000 Hz)"
          % __version__)
    scenes = build_scenes()
    bad = 0
    if not args.check:
        os.makedirs(args.out, exist_ok=True)
    for name in SCENE_FILES:
        data, info = scenes[name]
        path = os.path.join(args.out, name)
        if args.check:
            try:
                with open(path, "rb") as fh:
                    same = fh.read() == data
            except OSError:
                same = False
            status = "identical" if same else "DIFFERENT"
            bad += 0 if same else 1
        else:
            with open(path, "wb") as fh:
                fh.write(data)
            status = "written"
        print("  %-24s %-9s %s" % (name, status, describe(name, info)))
    print("Synthetic sonification only: not a recording, not an ECG or EEG,"
          " not a medical device.")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
